"""Deterministic C++11 headers: fields, CDR, maxSerializedSize, Lite flag."""

from __future__ import annotations

from typing import Callable, List, Optional, Sequence

from rosduino_gen.ast import (
    InterfaceSpec,
    StructureSpec,
    include_guard,
    snake_name,
)
from rosduino_gen.hashutil import format_c_bytes
from rosduino_gen.types import (
    DEFAULT_SEQ_CAP,
    DEFAULT_STRING_CAP,
    ParsedType,
    cpp_constant,
    cpp_field,
    fits_lite,
    max_serialized_size,
    nested_include,
    parse_type,
)

GENERATED_BANNER = "Generated by rosduino-gen. Do not edit."

ResolveFn = Callable[[str], Optional[InterfaceSpec]]


def _normalize_source(text: str) -> List[str]:
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = [line.rstrip() for line in normalized.split("\n")]
    while lines and lines[-1] == "":
        lines.pop()
    return lines


def _reconstruct_source(spec: InterfaceSpec) -> str:
    def struct_lines(structure: Optional[StructureSpec]) -> List[str]:
        if structure is None:
            return []
        lines: List[str] = []
        for const in structure.constants:
            lines.append(f"{const.type_expr} {const.name}={const.value}")
        for field in structure.fields:
            lines.append(f"{field.type_expr} {field.name}")
        return lines

    if spec.kind == "srv":
        return "\n".join(struct_lines(spec.request) + ["---"] + struct_lines(spec.response))
    return "\n".join(struct_lines(spec.request))


def _source_comment_block(spec: InterfaceSpec) -> str:
    if spec.source_text is not None:
        body = _normalize_source(spec.source_text)
    else:
        body = _normalize_source(_reconstruct_source(spec))
    lines = [
        f"// {GENERATED_BANNER}",
        "//",
        f"// {spec.type_name}",
        "//",
    ]
    for line in body:
        lines.append(f"// {line}" if line else "//")
    return "\n".join(lines)


def _type_helpers(detail: str, type_name: str, digest: bytes) -> str:
    encoded = format_c_bytes(digest)
    return f"""namespace {detail} {{

#if defined(__AVR__)
static const char kTypeName[] PROGMEM = "{type_name}";
static const uint8_t kTypeHash[8] PROGMEM = {{{encoded}}};
#else
static const char kTypeName[] = "{type_name}";
static const uint8_t kTypeHash[8] = {{{encoded}}};
#endif

}}  // namespace {detail}
"""


def _type_methods(detail: str, type_name: str) -> str:
    name_len = len(type_name)
    return f"""  static rosduino::core::StrView typeName() {{
#if defined(__AVR__)
    return rosduino::core::StrView({detail}::kTypeName, {name_len}U, true);
#else
    return rosduino::core::StrView::fromCString({detail}::kTypeName);
#endif
  }}

  static const uint8_t* typeHashBytes() {{ return {detail}::kTypeHash; }}

  static bool typeHashInProgmem() {{
#if defined(__AVR__)
    return true;
#else
    return false;
#endif
  }}
"""


# Parameter names must not match ROS field names (Quaternion.w, ColorRGBA.r).
def _write_expr(parsed: ParsedType, accessor: str, wr: str = "writer") -> str:
    if parsed.kind == "primitive" or parsed.kind == "string":
        return f"{wr}.{parsed.write_fn}({accessor})"
    if parsed.kind == "nested":
        return f"{accessor}.serialize({wr})"
    if parsed.kind == "array" and parsed.elem is not None and parsed.bound is not None:
        inner = _write_expr(parsed.elem, "item", "wr")
        return (
            f"{wr}.writeArray({accessor}, {parsed.bound}U, "
            f"[](rosduino::core::CdrWriter& wr, const {parsed.elem.cpp}& item) {{ "
            f"return {inner}; }})"
        )
    if parsed.kind == "sequence" and parsed.elem is not None:
        inner = _write_expr(parsed.elem, "item", "wr")
        return (
            f"{wr}.writeSequence({accessor}, "
            f"[](rosduino::core::CdrWriter& wr, const {parsed.elem.cpp}& item) {{ "
            f"return {inner}; }})"
        )
    raise ValueError(f"cannot serialize {parsed.ros}")


def _read_expr(parsed: ParsedType, accessor: str, rd: str = "reader") -> str:
    if parsed.kind == "primitive" or parsed.kind == "string":
        return f"{rd}.{parsed.read_fn}(&{accessor})"
    if parsed.kind == "nested":
        return f"{accessor}.deserialize({rd})"
    if parsed.kind == "array" and parsed.elem is not None and parsed.bound is not None:
        inner = _read_elem(parsed.elem)
        return (
            f"{rd}.readArray({accessor}, {parsed.bound}U, "
            f"[](rosduino::core::CdrReader& rd, {parsed.elem.cpp}* item) {{ "
            f"return {inner}; }})"
        )
    if parsed.kind == "sequence" and parsed.elem is not None:
        inner = _read_elem(parsed.elem)
        return (
            f"{rd}.readSequence(&{accessor}, "
            f"[](rosduino::core::CdrReader& rd, {parsed.elem.cpp}* item) {{ "
            f"return {inner}; }})"
        )
    raise ValueError(f"cannot deserialize {parsed.ros}")


def _read_elem(parsed: ParsedType) -> str:
    if parsed.kind == "primitive" or parsed.kind == "string":
        return f"rd.{parsed.read_fn}(item)"
    if parsed.kind == "nested":
        return "item->deserialize(rd)"
    raise ValueError(f"cannot deserialize element {parsed.ros}")


def _chain(indent: str, exprs: Sequence[str], method: str) -> str:
    if len(exprs) == 1:
        return f"{indent}bool {method} {{ return {exprs[0]}; }}\n"
    lines = [f"{indent}bool {method} {{", f"{indent}  return {exprs[0]} &&"]
    for expr in exprs[1:-1]:
        lines.append(f"{indent}         {expr} &&")
    lines.append(f"{indent}         {exprs[-1]};")
    lines.append(f"{indent}}}")
    return "\n".join(lines) + "\n"


def _empty_fields(indent: str) -> str:
    return (
        f"{indent}uint8_t structure_needs_at_least_one_member;\n\n"
        f"{indent}bool serialize(rosduino::core::CdrWriter& writer) const {{\n"
        f"{indent}  return writer.writeUInt8(structure_needs_at_least_one_member);\n"
        f"{indent}}}\n\n"
        f"{indent}bool deserialize(rosduino::core::CdrReader& reader) {{\n"
        f"{indent}  return reader.readUInt8(&structure_needs_at_least_one_member);\n"
        f"{indent}}}\n"
    )


def _structure_body(
    structure: StructureSpec,
    package: str,
    indent: str,
    default_seq_cap: int,
    size: int,
) -> str:
    chunks: List[str] = []
    for const in structure.constants:
        chunks.append(f"{indent}{cpp_constant(const.type_expr, const.name, const.value)}\n")
    if structure.constants:
        chunks.append("\n")
    if not structure.fields:
        chunks.append(_empty_fields(indent))
        lite = "true" if fits_lite(size) else "false"
        chunks.append(
            f"\n{indent}static constexpr size_t maxSerializedSize() {{ return {size}U; }}\n"
            f"{indent}static constexpr bool ROSDUINO_FITS_LITE = {lite};\n"
        )
        return "".join(chunks)

    writes: List[str] = []
    reads: List[str] = []
    for field in structure.fields:
        parsed = parse_type(field.type_expr, package, default_seq_cap)
        chunks.append(cpp_field(parsed, field.name, indent) + "\n")
        writes.append(_write_expr(parsed, field.name))
        reads.append(_read_expr(parsed, field.name))
    chunks.append("\n")
    ser_indent = indent
    chunks.append(
        _chain(ser_indent, writes, "serialize(rosduino::core::CdrWriter& writer) const")
    )
    chunks.append("\n")
    chunks.append(_chain(ser_indent, reads, "deserialize(rosduino::core::CdrReader& reader)"))
    lite = "true" if fits_lite(size) else "false"
    chunks.append(
        f"\n{indent}static constexpr size_t maxSerializedSize() {{ return {size}U; }}\n"
        f"{indent}static constexpr bool ROSDUINO_FITS_LITE = {lite};\n"
    )
    return "".join(chunks)


def _collect_includes(
    spec: InterfaceSpec,
    default_seq_cap: int,
) -> List[str]:
    found: List[str] = []
    seen = set()

    def walk(structure: Optional[StructureSpec]) -> None:
        if structure is None:
            return
        for field in structure.fields:
            parsed = parse_type(field.type_expr, spec.package, default_seq_cap)
            inc = nested_include(parsed)
            if inc and inc not in seen:
                seen.add(inc)
                found.append(inc)

    walk(spec.request)
    walk(spec.response)
    self_inc = f"{spec.package}/{spec.kind}/{spec.name}.h"
    return [path for path in found if path != self_inc]


def render_header(
    spec: InterfaceSpec,
    digest: bytes,
    *,
    default_seq_cap: int = DEFAULT_SEQ_CAP,
    string_cap: int = DEFAULT_STRING_CAP,
    emit_alias: bool = True,
    resolve: Optional[ResolveFn] = None,
) -> str:
    def lookup(type_name: str) -> Optional[InterfaceSpec]:
        if resolve is None:
            return None
        return resolve(type_name)

    guard = include_guard(spec.package, spec.kind, spec.name)
    detail = f"{snake_name(spec.name)}_detail"
    methods = _type_methods(detail, spec.type_name)
    helpers = _type_helpers(detail, spec.type_name, digest)
    includes = _collect_includes(spec, default_seq_cap)
    include_block = "".join(f"#include <{path}>\n" for path in includes)
    if includes:
        include_block += "\n"

    if spec.kind == "srv":
        req_size = max_serialized_size(spec, lookup, default_seq_cap, string_cap, "request")
        resp_size = max_serialized_size(spec, lookup, default_seq_cap, string_cap, "response")
        srv_size = max(req_size, resp_size)
        req_body = _structure_body(spec.request, spec.package, "    ", default_seq_cap, req_size)
        resp_body = _structure_body(
            spec.response or StructureSpec((), ()),
            spec.package,
            "    ",
            default_seq_cap,
            resp_size,
        )
        lite = "true" if fits_lite(srv_size) else "false"
        body = (
            f"struct {spec.name} {{\n"
            f"  struct Request {{\n{req_body}  }};\n"
            f"  struct Response {{\n{resp_body}  }};\n"
            f"  Request request;\n"
            f"  Response response;\n\n"
            f"{methods}"
            f"  static constexpr size_t maxSerializedSize() {{ return {srv_size}U; }}\n"
            f"  static constexpr bool ROSDUINO_FITS_LITE = {lite};\n"
            f"}};\n"
        )
    else:
        size = max_serialized_size(spec, lookup, default_seq_cap, string_cap, "message")
        fields = _structure_body(spec.request, spec.package, "  ", default_seq_cap, size)
        body = f"struct {spec.name} {{\n{fields}\n{methods}}};\n"

    alias = f"using {spec.kind}::{spec.name};\n" if emit_alias else ""
    source_block = _source_comment_block(spec)

    return f"""// SPDX-License-Identifier: Apache-2.0
{source_block}
#ifndef {guard}
#define {guard}

#include <stdint.h>

#if defined(__AVR__)
#include <avr/pgmspace.h>
#endif

{include_block}#include "rosduino/core/cdr.h"
#include "rosduino/core/commands.h"

namespace {spec.package} {{
namespace {spec.kind} {{
{helpers}
{body}
}}  // namespace {spec.kind}

{alias}
}}  // namespace {spec.package}

#endif  // {guard}
"""
